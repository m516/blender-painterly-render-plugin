"""tools/gen_svm_switch.py (T6.2): the switch it builds from vendored fragments.

Tests 1-4 run on a cut-down `kernel/svm/svm.h` whose fragments a temporary checkout and manifest
hold, so they need no network. Test 5 runs the script twice on the committed inputs, which are
the files that later cards add cases to.
"""


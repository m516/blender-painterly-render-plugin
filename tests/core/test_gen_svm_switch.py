# The three spans of the card's step 4, which surround the cases.
SPANS = (
    (
        "svm_case_macro",
        "#ifdef __KERNEL_USE_DATA_CONSTANTS__",
        "#endif",
    ),
    (
        "svm_eval_nodes_head",
        "/* Main Interpreter Loop */",
        "    switch (node_type) {",
    ),
    (
        "svm_eval_nodes_tail",
        "      default:",
        "}",
    ),
)


def _build_tree(root: Path) -> tuple[Path, Path]:
    """A checkout with GEN, a manifest with the three cases, and returns (manifest, vendored)."""
    checkout = root / "co"
    source = checkout / "intern" / "cycles" / "kernel" / "svm" / "svm.h"
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_bytes(GEN.encode("utf-8"))
    vendored = root / "tp" / "VENDORED.toml"
    vendored.parent.mkdir(parents=True)
    vendored.write_bytes(TEST_UPSTREAM.encode("utf-8"))
    checkouts = {"cycles": checkout}
    vs.add_fragments(
        vendored,
        checkouts,
        "cycles",
        "kernel/svm/svm.h",
        "svm_case",
        ["NODE_END", "NODE_MATH", "NODE_CLAMP"],
    )
    for fragment_id, begin, end in SPANS:
        vs.add_fragments(
            vendored,
            checkouts,
            "cycles",
            "kernel/svm/svm.h",
            "span",
            fragment_id=fragment_id,
            begin=begin,
            end=end,
        )
    manifest = root / "svm_nodes.toml"
    manifest.write_text(
        'includes = ["kernel/svm/util.h", "kernel/svm/math.h"]\n'
        'cases = ["NODE_MATH", "NODE_CLAMP", "NODE_END"]\n',
        encoding="utf-8",
    )
    return manifest, vendored


def _set_cases(manifest: Path, cases: str) -> None:
    """Rewrite the `cases` line of manifest."""
    lines = manifest.read_text(encoding="utf-8").splitlines(keepends=True)
    manifest.write_text(
        "".join(f"cases = {cases}\n" if line.startswith("cases = ") else line for line in lines),
        encoding="utf-8",
    )


def test_golden(tmp_path: Path) -> None:
    """The generated switch is EXPECTED, byte for byte."""
    assert hashlib.sha256(EXPECTED.encode()).hexdigest() == (
        "14e75e22bd9ffcc280036cf6762278c69b64806b60f0e97c18f9b826f9215553"
    )
    assert gen.generate(*_build_tree(tmp_path)) == EXPECTED


def test_cases_follow_upstream_order(tmp_path: Path) -> None:
    """The manifest's order does not matter: the cases come out in upstream order."""
    manifest, vendored = _build_tree(tmp_path)
    _set_cases(manifest, '["NODE_END", "NODE_CLAMP", "NODE_MATH"]')
    assert gen.generate(manifest, vendored) == EXPECTED


def test_raytrace_cases_share_a_conditional(tmp_path: Path) -> None:
    """Neither __SHADER_RAYTRACE__ case can be extracted: each lies in the shared conditional."""
    _, vendored = _build_tree(tmp_path)
    checkouts = {"cycles": tmp_path / "co"}
    for case in ("NODE_BEVEL", "NODE_AMBIENT_OCCLUSION"):
        with pytest.raises(vs.FragmentError):
            vs.add_fragments(vendored, checkouts, "cycles", "kernel/svm/svm.h", "svm_case", [case])


def test_main_rejects_each_bad_input(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """Every exit-1 condition of the card's test 4, and the --output/--check round trip."""
    variants = {
        "duplicate": '["NODE_MATH", "NODE_CLAMP", "NODE_END", "NODE_END"]',
        "missing": '["NODE_MATH", "NODE_CLAMP", "NODE_END", "NODE_INVERT"]',
    }
    for variant, cases in variants.items():
        manifest, vendored = _build_tree(tmp_path / variant)
        _set_cases(manifest, cases)
        out = tmp_path / variant / "out.h"
        assert (
            gen.main(
                ["--manifest", str(manifest), "--vendored", str(vendored), "--output", str(out)]
            )
            == 1
        )
        assert not out.exists()

    manifest, vendored = _build_tree(tmp_path / "key")
    with manifest.open("a", encoding="utf-8") as handle:
        handle.write("extra = 1\n")
    out = tmp_path / "key" / "out.h"
    assert (
        gen.main(["--manifest", str(manifest), "--vendored", str(vendored), "--output", str(out)])
        == 1
    )

    manifest, vendored = _build_tree(tmp_path / "sha")
    case_file = vendored.parent / "fragments/kernel/svm/svm_h/svm_case/NODE_MATH.inc"
    case_file.write_bytes(case_file.read_bytes() + b"x")
    out = tmp_path / "sha" / "out.h"
    assert (
        gen.main(["--manifest", str(manifest), "--vendored", str(vendored), "--output", str(out)])
        == 1
    )
    assert "sha256" in capsys.readouterr().err

    manifest, vendored = _build_tree(tmp_path / "check")
    out = tmp_path / "check" / "svm_eval_nodes.h"
    out.write_text(gen.generate(manifest, vendored) + "x", encoding="utf-8")
    assert (
        gen.main(["--manifest", str(manifest), "--vendored", str(vendored), "--check", str(out)])
        == 1
    )

    manifest, vendored = _build_tree(tmp_path / "ok")
    out = tmp_path / "ok" / "new" / "dir" / "svm_eval_nodes.h"
    assert (
        gen.main(["--manifest", str(manifest), "--vendored", str(vendored), "--output", str(out)])
        == 0
    )
    assert out.is_file()
    assert (
        gen.main(["--manifest", str(manifest), "--vendored", str(vendored), "--check", str(out)])
        == 0
    )


def test_committed_inputs(tmp_path: Path) -> None:
    """The committed manifest and fragments generate the same text from two working directories."""
    manifest = REPO_ROOT / "src" / "cycles" / "svm_nodes.toml"
    vendored = REPO_ROOT / "third_party" / "cycles" / "VENDORED.toml"
    outputs = []
    for index, seed in enumerate(("0", "1")):
        workdir = tmp_path / ("a" if index == 0 else "b")
        workdir.mkdir()
        out = workdir / "svm_eval_nodes.h"
        environment = {**os.environ, "PYTHONHASHSEED": seed}
        result = subprocess.run(
            [
                sys.executable,
                str(GEN_TOOL),
                "--manifest",
                str(manifest),
                "--vendored",
                str(vendored),
                "--output",
                str(out),
            ],
            capture_output=True,
            cwd=workdir,
            env=environment,
            check=False,
        )
        assert result.returncode == 0, result.stderr.decode()
        outputs.append(out.read_bytes())
    assert outputs[0] == outputs[1]
    assert outputs[0] == gen.generate(manifest, vendored).encode("utf-8")
    text = outputs[0].decode("utf-8")
    assert str(tmp_path) not in text
    assert str(REPO_ROOT) not in text
    # `cases` is a one-line array here (the card's test 5), so its entries are the quoted names.
    cases = tomllib.loads(manifest.read_text(encoding="utf-8"))["cases"]
    assert text.count("SVM_CASE(") == len(cases) + 2
    firsts = [
        int(line.split(":")[1].split("-")[0])
        for line in text.splitlines()
        if line.startswith("/* kernel/svm/svm.h:")
    ]
    assert firsts == sorted(firsts)
    assert len(set(firsts)) == len(firsts)

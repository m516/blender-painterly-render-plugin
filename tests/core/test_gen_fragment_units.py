"""tools/gen_fragment_units.py: one translation unit per fragmented upstream file (card T6.4).

The tests build their own checkout, manifest and fragment files with vendor_sync's Python API, so
none of them needs the network or the upstream checkout. The last test checks the committed
manifest against the committed fragments.
"""

import hashlib
import importlib.util
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
GEN_TOOL = REPO_ROOT / "tools" / "gen_fragment_units.py"
VENDOR_TOOL = REPO_ROOT / "tools" / "vendor_sync.py"
# The pinned [upstream.cycles] of the temporary manifests, as TEST_MANIFEST in
# test_vendor_fragments.py uses it.
UPSTREAM_TABLE = """[upstream.cycles]
repo = "https://github.com/blender/blender.git"
tag = "v5.2.2"
commit = "d13f752e3b9c4f8c261cda552b1021f8bcc0382c"
root = "intern/cycles"
"""


def _load(path: Path, name: str) -> ModuleType:
    """A tools script, loaded by path as test_vendor_fragments.py loads vendor_sync."""
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


gen = _load(GEN_TOOL, "gen_fragment_units")
vs = _load(VENDOR_TOOL, "vendor_sync_for_gen")


TOY = r"""/* SPDX-FileCopyrightText: 2011-2022 Blender Foundation
 *
 * SPDX-License-Identifier: Apache-2.0 */

#include "scene/toy_nodes.h"

CCL_NAMESPACE_BEGIN

static int toy_helper(const int a)
{
  return a + 1;
}

NODE_DEFINE(ToyNode)
{
  NodeType *type = NodeType::add("toy", create, NodeType::SHADER);
  SOCKET_IN_FLOAT(value, "Value", 0.0f);
  return type;
}

ToyNode::ToyNode() : ShaderNode(get_node_type()) {}

void ToyNode::compile(SVMCompiler &compiler)
{
  compiler.add_node(NODE_END);
}

void ToyNode::compile(OSLCompiler &compiler)
{
  compiler.add(this, "node_toy");
}

NODE_DEFINE(OtherNode)
{
  NodeType *type = NodeType::add("other", create, NodeType::SHADER);
  return type;
}

OtherNode::OtherNode() : ShaderNode(get_node_type()) {}

CCL_NAMESPACE_END
"""

UNITS = r"""[unit.toy]
upstream_path = "scene/toy_nodes.cpp"
includes = ["scene/toy_nodes.h", "<mutex>"]
node_registry = true
"""

EXPECTED = r"""/* Generated by tools/gen_fragment_units.py. Do not edit.
 *
 * Cycles scene/toy_nodes.cpp (Blender v5.2.2), restricted to its fragments in
 * third_party/cycles/VENDORED.toml, in upstream order. The text after each provenance comment
 * is a verbatim fragment from third_party/cycles/fragments/.
 *
 * SPDX-FileCopyrightText: 2011-2022 Blender Foundation
 * SPDX-License-Identifier: Apache-2.0 */

#include "scene/toy_nodes.h"
#include <mutex>
#include "cycles/shader_node_registry.h"

CCL_NAMESPACE_BEGIN

/* scene/toy_nodes.cpp:9-12 */
static int toy_helper(const int a)
{
  return a + 1;
}

/* scene/toy_nodes.cpp:14-19 */
NODE_DEFINE(ToyNode)
{
  NodeType *type = NodeType::add("toy", create, NodeType::SHADER);
  SOCKET_IN_FLOAT(value, "Value", 0.0f);
  return type;
}

/* scene/toy_nodes.cpp:21-21 */
ToyNode::ToyNode() : ShaderNode(get_node_type()) {}

/* scene/toy_nodes.cpp:23-26 */
void ToyNode::compile(SVMCompiler &compiler)
{
  compiler.add_node(NODE_END);
}

/* scene/toy_nodes.cpp:33-37 */
NODE_DEFINE(OtherNode)
{
  NodeType *type = NodeType::add("other", create, NodeType::SHADER);
  return type;
}

/* Node type registry (card T6.4): one reference to the get_node_type() of every NODE_DEFINE
 * fragment above, in upstream order, so that linking this function links every node type.
 * Declared in src/cycles/shader_node_registry.h. */
const std::vector<const NodeType *> &painterly_cycles_shader_node_types()
{
  static const std::vector<const NodeType *> types = {
      ToyNode::get_node_type(),
      OtherNode::get_node_type(),
  };
  return types;
}

CCL_NAMESPACE_END
"""


def _setup(tmp_path: Path) -> tuple[Path, Path, Path]:
    """The toy checkout, manifest and units.toml of tests 1-4, with the five fragments added.

    Returns (units, vendored, manifest). The four add_fragments calls are the card's; the
    node_define call passes OtherNode first, so the manifest order differs from upstream's.
    """
    checkout = tmp_path / "co"
    source = checkout / "intern" / "cycles" / "scene" / "toy_nodes.cpp"
    source.parent.mkdir(parents=True)
    source.write_bytes(TOY.encode("utf-8"))
    vendored = tmp_path / "tp" / "VENDORED.toml"
    vendored.parent.mkdir(parents=True)
    vendored.write_bytes(UPSTREAM_TABLE.encode("utf-8"))
    checkouts = {"cycles": checkout}
    vs.add_fragments(
        vendored,
        checkouts,
        "cycles",
        "scene/toy_nodes.cpp",
        "node_define",
        ["OtherNode", "ToyNode"],
    )
    vs.add_fragments(
        vendored,
        checkouts,
        "cycles",
        "scene/toy_nodes.cpp",
        "member",
        ["ToyNode::compile"],
        params="SVMCompiler",
    )
    vs.add_fragments(
        vendored, checkouts, "cycles", "scene/toy_nodes.cpp", "function", ["toy_helper"]
    )
    vs.add_fragments(
        vendored, checkouts, "cycles", "scene/toy_nodes.cpp", "member", ["ToyNode::ToyNode"]
    )
    units = tmp_path / "units.toml"
    units.write_bytes(UNITS.encode("utf-8"))
    return units, vendored, vendored


def _run(args: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    """Run the generator as a script from cwd, capturing its output."""
    return subprocess.run(
        [sys.executable, str(GEN_TOOL), *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        check=False,
    )


def test_generate_matches_expected(tmp_path: Path) -> None:
    """The five fragments, in upstream order, with the registry block; the frozen sha256 holds."""
    units, vendored, _ = _setup(tmp_path)
    assert gen.generate(units, vendored, "toy") == EXPECTED
    assert (
        hashlib.sha256(EXPECTED.encode()).hexdigest()
        == "87ef6942ffdccf5af2691837b97bd75eba3c8fa75b3345aa794e752d53bc9ade"
    )


def _manifest_variant(tmp_path: Path, text: str, name: str = "units.toml") -> Path:
    """A units.toml holding text, under its own name, so it cannot replace the shared one."""
    path = tmp_path / name
    path.write_bytes(text.encode("utf-8"))
    return path


def test_manifest_rules_are_rejected(tmp_path: Path) -> None:
    """A broken manifest, unit or fragment fails with exit 1 and the gen_fragment_units prefix."""
    units, vendored, _ = _setup(tmp_path)
    expected = gen.generate(units, vendored, "toy")

    cases = {
        "unknown unit": (units, vendored, "nope", None),
        "extra key": (
            _manifest_variant(
                tmp_path,
                UNITS.replace("node_registry", "extra = 1\nnode_registry"),
                "extra.toml",
            ),
            vendored,
            "toy",
            None,
        ),
        "no node_registry": (
            _manifest_variant(
                tmp_path, UNITS.replace("node_registry = true\n", ""), "no-registry.toml"
            ),
            vendored,
            "toy",
            None,
        ),
        "space in include": (
            _manifest_variant(
                tmp_path, UNITS.replace("scene/toy_nodes.h", "scene/toy nodes.h"), "space.toml"
            ),
            vendored,
            "toy",
            None,
        ),
        "include twice": (
            _manifest_variant(
                tmp_path, UNITS.replace('"<mutex>"', '"<mutex>", "<mutex>"'), "twice.toml"
            ),
            vendored,
            "toy",
            None,
        ),
        "two registries": (
            _manifest_variant(
                tmp_path,
                UNITS
                + '\n[unit.other]\nupstream_path = "scene/toy_nodes.cpp"\n'
                + "includes = []\nnode_registry = true\n",
                "two.toml",
            ),
            vendored,
            "toy",
            None,
        ),
        "no fragment": (
            _manifest_variant(
                tmp_path, UNITS.replace("scene/toy_nodes.cpp", "scene/none.cpp"), "none.toml"
            ),
            vendored,
            "toy",
            None,
        ),
        "check missing": (units, vendored, "toy", tmp_path / "missing.cpp"),
    }
    for label, (manifest, vendor, unit, check) in cases.items():
        args = [
            "--manifest",
            str(manifest),
            "--vendored",
            str(vendor),
            "--unit",
            unit,
        ]
        if check is None:
            out = tmp_path / f"out-{label.replace(' ', '-')}.cpp"
            args += ["--output", str(out)]
        else:
            args += ["--check", str(check)]
        result = _run(args, tmp_path)
        assert result.returncode == 1, label
        assert result.stderr.startswith("gen_fragment_units: "), label
    assert not (tmp_path / "missing.cpp").exists()

    # A changed fragment file fails on its sha256, and is put back.
    fragment = tmp_path / "tp" / "fragments" / "scene/toy_nodes_cpp/function/toy_helper.inc"
    original = fragment.read_bytes()
    fragment.write_bytes(original + b"\n")
    result = _run(
        [
            "--manifest",
            str(units),
            "--vendored",
            str(vendored),
            "--unit",
            "toy",
            "--output",
            str(tmp_path / "out-changed.cpp"),
        ],
        tmp_path,
    )
    assert result.returncode == 1
    assert "sha256" in result.stderr
    fragment.write_bytes(original)

    # --check against EXPECTED with its last byte removed fails, and writes nothing.
    short = tmp_path / "short.cpp"
    short.write_bytes(expected[:-1].encode("utf-8"))
    result = _run(
        [
            "--manifest",
            str(units),
            "--vendored",
            str(vendored),
            "--unit",
            "toy",
            "--check",
            str(short),
        ],
        tmp_path,
    )
    assert result.returncode == 1
    assert short.read_bytes() == expected[:-1].encode("utf-8")


def test_registry_needs_a_node_define(tmp_path: Path) -> None:
    """node_registry = true on a unit whose only fragment is a function fails."""
    checkout = tmp_path / "co"
    source = checkout / "intern" / "cycles" / "scene" / "toy_nodes.cpp"
    source.parent.mkdir(parents=True)
    source.write_bytes(TOY.encode("utf-8"))
    vendored = tmp_path / "tp2" / "VENDORED.toml"
    vendored.parent.mkdir(parents=True)
    vendored.write_bytes(UPSTREAM_TABLE.encode("utf-8"))
    vs.add_fragments(
        vendored, {"cycles": checkout}, "cycles", "scene/toy_nodes.cpp", "function", ["toy_helper"]
    )
    units = _manifest_variant(tmp_path, UNITS)
    with pytest.raises(gen.GenError):
        gen.generate(units, vendored, "toy")
    result = _run(
        [
            "--manifest",
            str(units),
            "--vendored",
            str(vendored),
            "--unit",
            "toy",
            "--output",
            str(tmp_path / "out.cpp"),
        ],
        tmp_path,
    )
    assert result.returncode == 1
    assert result.stderr.startswith("gen_fragment_units: ")


def test_check_and_output(tmp_path: Path) -> None:
    """--check accepts EXPECTED, and --output creates missing parent directories."""
    units, vendored, _ = _setup(tmp_path)
    same = tmp_path / "same.cpp"
    same.write_bytes(EXPECTED.encode("utf-8"))
    assert (
        _run(
            [
                "--manifest",
                str(units),
                "--vendored",
                str(vendored),
                "--unit",
                "toy",
                "--check",
                str(same),
            ],
            tmp_path,
        ).returncode
        == 0
    )
    fresh = tmp_path / "new" / "dir" / "toy.cpp"
    assert (
        _run(
            [
                "--manifest",
                str(units),
                "--vendored",
                str(vendored),
                "--unit",
                "toy",
                "--output",
                str(fresh),
            ],
            tmp_path,
        ).returncode
        == 0
    )
    assert fresh.read_bytes() == EXPECTED.encode("utf-8")


@pytest.mark.parametrize("unit", ["shader_nodes", "svm"])
def test_committed_units(tmp_path: Path, unit: str) -> None:
    """The committed manifest: reproducible, order-free, provenance comments complete."""
    manifest = REPO_ROOT / "src" / "cycles" / "fragment_units.toml"
    vendored = REPO_ROOT / "third_party" / "cycles" / "VENDORED.toml"
    outputs = []
    for index, seed in enumerate(("0", "1")):
        directory = tmp_path / chr(ord("a") + index)
        directory.mkdir()
        out = directory / f"{unit}.cpp"
        result = subprocess.run(
            [
                sys.executable,
                str(GEN_TOOL),
                "--manifest",
                str(manifest),
                "--vendored",
                str(vendored),
                "--unit",
                unit,
                "--output",
                str(out),
            ],
            cwd=directory,
            capture_output=True,
            text=True,
            check=False,
            env={"PYTHONHASHSEED": seed, "PATH": "/usr/bin:/bin"},
        )
        assert result.returncode == 0, result.stderr
        outputs.append(out.read_bytes())
    assert outputs[0] == outputs[1]
    text = outputs[0].decode("utf-8")
    assert text == gen.generate(manifest, vendored, unit)
    assert str(tmp_path) not in text
    assert str(REPO_ROOT) not in text

    with vendored.open("rb") as handle:
        import tomllib

        entries = [
            table
            for table in tomllib.load(handle).get("fragment", [])
            if table["upstream_path"]
            == f"scene/{'shader_nodes' if unit == 'shader_nodes' else 'svm'}.cpp"
        ]
    comments = re.findall(r"^/\* scene/[a-z_]+\.cpp:(\d+)-(\d+) \*/$", text, flags=re.MULTILINE)
    assert len(comments) == len(entries)
    firsts = [int(first) for first, _ in comments]
    assert firsts == sorted(firsts)
    assert len(set(firsts)) == len(firsts)

    if unit == "shader_nodes":
        anchors = [
            table["anchor"]
            for table in sorted(entries, key=lambda t: t["upstream_lines"][0])
            if table["kind"] == "node_define"
        ]
        found = re.findall(r"^      (\w+)::get_node_type\(\),$", text, flags=re.MULTILINE)
        assert found == anchors
    else:
        assert "painterly_cycles_shader_node_types" not in text

#!/usr/bin/env python3
"""Assemble one translation unit per fragmented upstream Cycles file (card T6.4).

The manifest (src/cycles/fragment_units.toml) names the units. A unit holds every [[fragment]]
entry of third_party/cycles/VENDORED.toml whose upstream_path is the unit's, in upstream order,
after the includes the manifest lists. The shader_nodes unit also defines the node type registry
painterly_cycles_shader_node_types(), which references every NODE_DEFINE fragment's
get_node_type(), so that linking it links every node type.

Usage:
  gen_fragment_units.py --manifest PATH --vendored PATH --unit NAME (--output PATH | --check PATH)

Exit status: 0 on success; 1, with "gen_fragment_units: <message>" on stderr, on any error.
Stdlib only (argparse, hashlib, pathlib, re, sys, tomllib).
"""

import argparse
import hashlib
import re
import sys
import tomllib
from pathlib import Path

# The provenance header of every unit, with <upstream_path> substituted. "Blender v5.2.2" is the
# [upstream.cycles] tag that VENDORED.toml pins.
HEADER = """/* Generated by tools/gen_fragment_units.py. Do not edit.
 *
 * Cycles <upstream_path> (Blender v5.2.2), restricted to its fragments in
 * third_party/cycles/VENDORED.toml, in upstream order. The text after each provenance comment
 * is a verbatim fragment from third_party/cycles/fragments/.
 *
 * SPDX-FileCopyrightText: 2011-2022 Blender Foundation
 * SPDX-License-Identifier: Apache-2.0 */
"""

# The node type registry, defined in the same unit as the NODE_DEFINE fragments it references.
# The get_node_type() lines go between the line ending in "{" and the line "  };".
REGISTRY = (  # noqa: E501 - the block is the card's text, verbatim, so it is not rewrapped.
    """/* Node type registry (card T6.4): one reference to the get_node_type() of every NODE_DEFINE
 * fragment above, in upstream order, so that linking this function links every node type.
 * Declared in src/cycles/shader_node_registry.h. */
const std::vector<const NodeType *> &painterly_cycles_shader_node_types()
{
  static const std::vector<const NodeType *> types = {
  };
  return types;
}
"""
)

# A unit's name: lowercase letters and underscores, so that it is a safe file name.
UNIT_NAME_RE = re.compile(r"[a-z_]+")
# A header path, e.g. "scene/shader_nodes.h" or "kernel/svm/math_types.h".
HEADER_PATH_RE = re.compile(r"[A-Za-z0-9_./]+\.h")
# A system header, e.g. "<mutex>".
SYSTEM_HEADER_RE = re.compile(r"<[a-z_]+>")
# The upstream name whose [[fragment]] entries a unit collects.
UPSTREAM = "cycles"
# The keys of a [unit.<name>] table, and the ones it must have.
UNIT_KEYS = frozenset({"upstream_path", "includes", "node_registry"})
# The kind of fragment whose anchor the registry references.
REGISTRY_KIND = "node_define"


class GenError(Exception):
    """A broken manifest, a missing or changed fragment file, or a unit that cannot be built."""


def _load_toml(path: Path, what: str) -> dict:
    """The TOML table of path, decoded as UTF-8, or GenError naming it."""
    try:
        with path.open("rb") as handle:
            return tomllib.load(handle)
    except OSError as err:
        raise GenError(f"cannot read the {what} {path}: {err}") from err
    except tomllib.TOMLDecodeError as err:
        raise GenError(f"the {what} {path} is not valid TOML: {err}") from err


def _unit(manifest: dict, unit: str, path: Path) -> tuple[str, list[str], bool]:
    """The upstream_path, includes and node_registry of [unit.<name>], checked against the rules."""
    if UNIT_NAME_RE.fullmatch(unit) is None:
        raise GenError(f"the unit name {unit!r} is not lowercase letters and underscores")
    units = manifest.get("unit")
    if not isinstance(units, dict):
        raise GenError(f"the manifest {path} has no [unit.<name>] table")
    # The whole manifest is checked, not only the requested unit: at most one unit may set
    # node_registry, because the registry function is defined once (card T6.4, "Interface").
    registries = [
        name
        for name, table in units.items()
        if isinstance(table, dict) and table.get("node_registry") is True
    ]
    if len(registries) > 1:
        raise GenError(f"the manifest {path} sets node_registry in {len(registries)} units")
    if unit not in units:
        raise GenError(f"the manifest {path} has no unit {unit!r}")
    table = units[unit]
    if not isinstance(table, dict):
        raise GenError(f"[unit.{unit}] is not a table")
    extra = sorted(set(table) - UNIT_KEYS)
    missing = sorted(UNIT_KEYS - set(table))
    if extra or missing:
        raise GenError(
            f"[unit.{unit}] takes {sorted(UNIT_KEYS)}; missing {missing}, unexpected {extra}"
        )

    upstream_path = table["upstream_path"]
    if not isinstance(upstream_path, str) or not upstream_path:
        raise GenError(f"[unit.{unit}]: upstream_path must be a non-empty string")

    includes = table["includes"]
    if not isinstance(includes, list) or not all(isinstance(item, str) for item in includes):
        raise GenError(f"[unit.{unit}]: includes must be an array of strings")
    for item in includes:
        if HEADER_PATH_RE.fullmatch(item) is None and SYSTEM_HEADER_RE.fullmatch(item) is None:
            raise GenError(f"[unit.{unit}]: {item!r} is not a header path or a system header")
    if len(set(includes)) != len(includes):
        raise GenError(f"[unit.{unit}]: includes lists a header twice")

    node_registry = table["node_registry"]
    if not isinstance(node_registry, bool):
        raise GenError(f"[unit.{unit}]: node_registry must be a boolean")
    return upstream_path, includes, node_registry


def _fragments(vendored: dict, upstream_path: str) -> list[dict]:
    """The [[fragment]] entries of upstream_path, in upstream order, checked against the rules."""
    entries = vendored.get("fragment", [])
    if not isinstance(entries, list):
        raise GenError("VENDORED.toml: fragment must be an array of tables")
    mine = []
    for table in entries:
        if not isinstance(table, dict):
            raise GenError("VENDORED.toml: every [[fragment]] table must be a table")
        if table.get("upstream") != UPSTREAM or table.get("upstream_path") != upstream_path:
            continue
        for key in ("name", "kind", "upstream_lines", "sha256"):
            if key not in table:
                raise GenError(f"[[fragment]] {table.get('name')!r}: no {key!r}")
        mine.append(table)
    mine.sort(key=lambda table: table["upstream_lines"][0])
    return mine


def _fragment_bytes(directory: Path, table: dict) -> bytes:
    """The bytes of one fragment's .inc file, checked against the entry's sha256."""
    name = table["name"]
    path = directory / f"{name}.inc"
    try:
        data = path.read_bytes()
    except OSError as err:
        raise GenError(f"cannot read the fragment {name}: {err}") from err
    digest = hashlib.sha256(data).hexdigest()
    if digest != table["sha256"]:
        raise GenError(
            f"the fragment {name} has sha256 {digest}, but VENDORED.toml records {table['sha256']}"
        )
    return data


def generate(manifest: Path, vendored: Path, unit: str) -> str:
    """The text of one generated translation unit. Raises GenError on any broken input."""
    units = _load_toml(manifest, "manifest")
    upstream_path, includes, node_registry = _unit(units, unit, manifest)
    tables = _fragments(_load_toml(vendored, "vendored manifest"), upstream_path)
    if not tables:
        raise GenError(f"the unit {unit!r} has no fragment of {upstream_path}")
    if node_registry and not any(table["kind"] == REGISTRY_KIND for table in tables):
        raise GenError(f"the unit {unit!r} sets node_registry but has no {REGISTRY_KIND} fragment")

    directory = vendored.parent / "fragments"
    parts = [HEADER.replace("<upstream_path>", upstream_path), "\n"]
    for item in includes:
        parts.append(
            f"#include <{item[1:-1]}>\n" if item.startswith("<") else f'#include "{item}"\n'
        )
    if node_registry:
        parts.append('#include "cycles/shader_node_registry.h"\n')
    parts.append("\nCCL_NAMESPACE_BEGIN\n\n")
    for table in tables:
        first, last = table["upstream_lines"]
        parts.append(f"/* {upstream_path}:{first}-{last} */\n")
        parts.append(_fragment_bytes(directory, table).decode("utf-8"))
        parts.append("\n")
    if node_registry:
        anchor_lines = "".join(
            f"      {table['anchor']}::get_node_type(),\n"
            for table in tables
            if table["kind"] == REGISTRY_KIND
        )
        parts.append(REGISTRY.replace("  };\n", anchor_lines + "  };\n"))
        parts.append("\n")
    parts.append("CCL_NAMESPACE_END\n")
    return "".join(parts)


def build_parser() -> argparse.ArgumentParser:
    """The command line: the two TOML inputs, the unit, and exactly one of --output and --check."""
    parser = argparse.ArgumentParser(
        prog="gen_fragment_units.py",
        description="Assemble one translation unit from the fragments of an upstream Cycles file.",
    )
    parser.add_argument("--manifest", required=True, type=Path, help="the unit manifest TOML")
    parser.add_argument("--vendored", required=True, type=Path, help="third_party VENDORED.toml")
    parser.add_argument("--unit", required=True, help="the [unit.<name>] to build")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--output", type=Path, help="write the unit here, creating parents")
    group.add_argument("--check", type=Path, help="compare an existing file with the unit")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Run one command and return its exit status: 0 on success, 1 on any GenError."""
    args = build_parser().parse_args(argv)
    try:
        text = generate(args.manifest, args.vendored, args.unit)
        data = text.encode("utf-8")
        if args.output is not None:
            try:
                args.output.parent.mkdir(parents=True, exist_ok=True)
                args.output.write_bytes(data)
            except OSError as err:
                raise GenError(f"cannot write {args.output}: {err}") from err
        else:
            try:
                existing = args.check.read_bytes()
            except OSError as err:
                raise GenError(f"cannot read {args.check}: {err}") from err
            if existing != data:
                raise GenError(f"{args.check} differs from the generated unit {args.unit}")
    except GenError as err:
        print(f"gen_fragment_units: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

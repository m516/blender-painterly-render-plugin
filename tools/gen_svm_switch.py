#!/usr/bin/env python3
"""Cycles' svm_eval_nodes() built from vendored fragments (T6.2).

The output is the upstream function's frame (its signature and loop, from the `svm_eval_nodes_head`
and `svm_eval_nodes_tail` fragments) with the `SVM_CASE` blocks of the nodes listed in
src/cycles/svm_nodes.toml. Every block is a verbatim fragment from third_party/cycles/fragments/,
whose sha256 is recorded in third_party/cycles/VENDORED.toml and checked before use.

Usage:

  gen_svm_switch.py --manifest PATH --vendored PATH --output PATH
                              write the switch to PATH, creating missing directories
  gen_svm_switch.py --manifest PATH --vendored PATH --check PATH
                              compare PATH with the switch that would be generated

Exit status: 0 on success, 1 when an input cannot produce the switch (with
`gen_svm_switch: <message>` on stderr), 2 on a usage error. The output depends only on its two
inputs, so it is reproducible byte for byte; later cards add cases without changing this tool.
"""

import argparse
import hashlib
import re
import sys
import tomllib
from pathlib import Path

# The three fragments that surround the cases: the SVM_CASE macro, and the head and tail of
# svm_eval_nodes() around its switch. They are spans of kernel/svm/svm.h (T6.2, "Anchor kinds").
MACRO_FRAGMENT = "kernel/svm/svm_h/span/svm_case_macro"
HEAD_FRAGMENT = "kernel/svm/svm_h/span/svm_eval_nodes_head"
TAIL_FRAGMENT = "kernel/svm/svm_h/span/svm_eval_nodes_tail"
# A case NODE_X takes the fragment kernel/svm/svm_h/svm_case/NODE_X (src/cycles/svm_nodes.toml).
CASE_FRAGMENT_PREFIX = "kernel/svm/svm_h/svm_case/"
# The manifest's exactly two keys, and the text each value must match (src/cycles/svm_nodes.toml).
MANIFEST_KEYS = ("includes", "cases")
INCLUDE_RE = re.compile(r"[A-Za-z0-9_./]+\.h")
CASE_RE = re.compile(r"NODE_[A-Z0-9_]+")
# The manifest file that the header names as the source of the case list (the card's "For T6.3").
MANIFEST_NAME = "src/cycles/svm_nodes.toml"
SHA256_HEX_LEN = 64  # hex digits of a SHA-256 digest (FIPS 180-4)
HEADER = (
    "/* Generated by tools/gen_svm_switch.py. Do not edit.\n"
    " *\n"
    " * svm_eval_nodes() of Cycles kernel/svm/svm.h (Blender v5.2.2), restricted to the cases of\n"
    f" * {MANIFEST_NAME}. The text after each provenance comment is a verbatim fragment\n"
    " * from third_party/cycles/fragments/ (sha256 in third_party/cycles/VENDORED.toml).\n"
    " *\n"
    " * SPDX-FileCopyrightText: 2011-2022 Blender Foundation\n"
    " * SPDX-License-Identifier: Apache-2.0 */\n"
)


class GenerateError(Exception):
    """An input that cannot produce the switch. The message names the file, entry or case."""


def _sha256(data: bytes) -> str:
    """Lowercase hex SHA-256 digest of data."""
    return hashlib.sha256(data).hexdigest()


def _load_toml(path: Path, what: str) -> dict[str, object]:
    """The parsed TOML table of path; a read error or invalid TOML becomes GenerateError."""
    try:
        with path.open("rb") as handle:
            return tomllib.load(handle)
    except OSError as err:
        raise GenerateError(f"cannot read {what} {path}: {err}") from err
    except tomllib.TOMLDecodeError as err:
        raise GenerateError(f"{what} {path} is not valid TOML: {err}") from err


def _manifest(manifest: Path) -> tuple[list[str], list[str]]:
    """The includes and cases of src/cycles/svm_nodes.toml, checked for key, type and form."""
    data = _load_toml(manifest, "manifest")
    extra = sorted(set(data) - set(MANIFEST_KEYS))
    missing = sorted(set(MANIFEST_KEYS) - set(data))
    if extra or missing:
        raise GenerateError(
            f"manifest {manifest}: it has exactly the keys {list(MANIFEST_KEYS)};"
            f" missing {missing}, unexpected {extra}"
        )
    values: list[list[str]] = []
    for key, pattern in (("includes", INCLUDE_RE), ("cases", CASE_RE)):
        value = data[key]
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            raise GenerateError(f"manifest {manifest}: {key} must be an array of strings")
        for item in value:
            if pattern.fullmatch(item) is None:
                raise GenerateError(
                    f"manifest {manifest}: {key} entry {item!r} does not match {pattern.pattern}"
                )
        values.append(list(value))
    includes, cases = values
    seen: set[str] = set()
    for case in cases:
        if case in seen:
            raise GenerateError(f"manifest {manifest}: the case {case} is listed twice")
        seen.add(case)
    return includes, cases


def _fragments(vendored: Path) -> dict[str, dict[str, object]]:
    """The `[[fragment]]` entries of VENDORED.toml, keyed by name."""
    data = _load_toml(vendored, "vendored manifest")
    tables = data.get("fragment", [])
    if not isinstance(tables, list):
        raise GenerateError(f"{vendored}: `fragment` is not an array of tables")
    entries: dict[str, dict[str, object]] = {}
    for table in tables:
        name = table.get("name") if isinstance(table, dict) else None
        if not isinstance(name, str):
            raise GenerateError(f"{vendored}: a [[fragment]] entry has no name")
        entries[name] = table
    return entries


def _fragment_text(
    name: str, entries: dict[str, dict[str, object]], directory: Path
) -> tuple[str, str, int, int]:
    """The fragment's text, its upstream path and its line range, after checking its sha256."""
    if name not in entries:
        raise GenerateError(f"{name}: no [[fragment]] entry in third_party/cycles/VENDORED.toml")
    table = entries[name]
    path = directory / f"{name}.inc"
    try:
        data = path.read_bytes()
    except OSError as err:
        raise GenerateError(f"{name}: cannot read {path}: {err}") from err
    recorded = table.get("sha256")
    if _sha256(data) != recorded:
        raise GenerateError(
            f"{name}: {path} has sha256 {_sha256(data)}, but VENDORED.toml records {recorded}"
        )
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as err:
        raise GenerateError(f"{name}: {path} is not UTF-8: {err}") from err
    upstream_path = table.get("upstream_path")
    lines = table.get("upstream_lines")
    if (
        not isinstance(upstream_path, str)
        or not isinstance(lines, list)
        or len(lines) != 2
        or not all(isinstance(number, int) and not isinstance(number, bool) for number in lines)
    ):
        raise GenerateError(f"{name}: its entry lacks upstream_path or upstream_lines")
    first, last = lines
    return text, upstream_path, first, last


def _provenance(text: str, upstream_path: str, first: int, last: int) -> str:
    """P(f): the provenance comment, a newline, then the fragment's text."""
    return f"/* {upstream_path}:{first}-{last} */\n{text}"


def generate(manifest: Path, vendored: Path) -> str:
    """The switch text of these two inputs. Every failure raises GenerateError."""
    includes, cases = _manifest(manifest)
    entries = _fragments(vendored)
    directory = vendored.parent / "fragments"
    parts = [HEADER, "\n#pragma once\n\n"]
    parts += [f'#include "{include}"\n' for include in includes]
    parts.append("\nCCL_NAMESPACE_BEGIN\n\n")
    macro = _fragment_text(MACRO_FRAGMENT, entries, directory)
    parts.append(_provenance(*macro))
    parts.append("\n")
    head = _fragment_text(HEAD_FRAGMENT, entries, directory)
    parts.append(_provenance(*head))
    blocks = [_fragment_text(CASE_FRAGMENT_PREFIX + case, entries, directory) for case in cases]
    for block in sorted(blocks, key=lambda found: found[2]):
        parts.append(_provenance(*block))
    tail = _fragment_text(TAIL_FRAGMENT, entries, directory)
    parts.append(_provenance(*tail))
    parts.append("\nCCL_NAMESPACE_END\n")
    return "".join(parts)


def _write(output: Path, text: str) -> None:
    """Write the switch as bytes, creating missing parent directories."""
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(text.encode("utf-8"))
    except OSError as err:
        raise GenerateError(f"cannot write {output}: {err}") from err


def _check(path: Path, text: str) -> None:
    """Raise GenerateError unless path holds exactly the generated text."""
    try:
        existing = path.read_bytes()
    except OSError as err:
        raise GenerateError(f"cannot read {path}: {err}") from err
    if existing != text.encode("utf-8"):
        raise GenerateError(f"{path} differs from the generated text")


def build_parser() -> argparse.ArgumentParser:
    """The command line: two inputs, and either --output or --check."""
    parser = argparse.ArgumentParser(
        prog="gen_svm_switch.py",
        description="Generate Cycles' svm_eval_nodes() from vendored fragments.",
    )
    parser.add_argument("--manifest", required=True, type=Path, metavar="PATH")
    parser.add_argument("--vendored", required=True, type=Path, metavar="PATH")
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--output", type=Path, metavar="PATH", help="write the switch here")
    target.add_argument("--check", type=Path, metavar="PATH", help="compare this file with it")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Run the generator and return its exit status."""
    args = build_parser().parse_args(argv)
    try:
        text = generate(args.manifest, args.vendored)
        if args.output is not None:
            _write(args.output, text)
        else:
            _check(args.check, text)
    except GenerateError as err:
        print(f"gen_svm_switch: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
